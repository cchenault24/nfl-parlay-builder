import { Box, Typography } from '@mui/material'
import React from 'react'
import useParlayStore from '../../store/parlayStore'
import { LegalDisclaimer } from '../legal/LegalDisclaimer'

const ParlayDisplayFooter: React.FC = () => {
  const parlay = useParlayStore(state => state.parlay)
  if (!parlay) {
    return null
  }
  return (
    <Box
      sx={{
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'space-between',
        gap: 2,
        flexWrap: 'wrap',
      }}
    >
      <Typography variant="caption" color="text.secondary" sx={{ fontVariantNumeric: 'tabular-nums' }}>
        Overall confidence {Math.round(parlay.parlayConfidence * 100)}%
      </Typography>
      <LegalDisclaimer variant="inline" />
      <Typography variant="caption" color="text.secondary">
        Generated by {parlay.model}
      </Typography>
    </Box>
  )
}

export default ParlayDisplayFooter
